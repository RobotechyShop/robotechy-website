/**
 * Normalise a country code to ISO 3166-1 alpha-2 (uppercase). Accepts alpha-2
 * or alpha-3 input; returns undefined for anything unrecognisable.
 */
// O(1) validity lookups for toAlpha2 (COUNTRY_CODES is an array).
const COUNTRY_CODE_SET = new Set(COUNTRY_CODES);

export function toAlpha2(code: string): string | undefined {
  const upper = code.trim().toUpperCase();
  // Validate 2-letter codes against the assigned ISO set — an unassigned pair
  // like "ZZ" from external event data must NOT pass as a valid country.
  if (upper.length === 2) return COUNTRY_CODE_SET.has(upper) ? upper : undefined;
  if (upper.length === 3) return ALPHA3_TO_ALPHA2[upper];
  return undefined;
}

/** Localised display name for a country code (falls back to the code itself). */
export function countryName(code: string): string {
  try {
    const names = new Intl.DisplayNames(undefined, { type: 'region' });
    return names.of(code.toUpperCase()) || code.toUpperCase();
  } catch {
    return code.toUpperCase();
  }
}

export interface CountryEntry {
  code: string;
  name: string;
}

/** All countries as {code, name}, sorted by localised display name. */
export function allCountries(): CountryEntry[] {
  return COUNTRY_CODES.map((code) => ({ code, name: countryName(code) })).sort((a, b) =>
    a.name.localeCompare(b.name)
  );
}

/**
 * Best-effort ship-to default from the browser locale (e.g. "en-GB" -> "GB").
 * Returns undefined when the locale has no usable region subtag.
 */
export function detectLocaleCountry(): string | undefined {
  try {
    const locale = navigator.language;
    const region = new Intl.Locale(locale).region;
    return region && COUNTRY_CODES.includes(region.toUpperCase())
      ? region.toUpperCase()
      : undefined;
  } catch {
    return undefined;
  }
}
